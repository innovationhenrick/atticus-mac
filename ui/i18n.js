  const normalize = value => value.replace(/\u00a0/g, " ").replace(/\s+/g, " ").trim();

  function translate(value) {
    if (typeof value !== "string") return value;
    const compact = normalize(value);
    if (!compact || compact.length > 5000) return value;
    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    let result = exact[compact];
    if (result !== undefined) return leading + result + trailing;
    for (const [pattern, render] of patterns) {
      const match = compact.match(pattern);
      if (match) return leading + render(...match) + trailing;
    }
    return value;
  }

  const skipElement = element => !element || !!element.closest("script,style,code,pre,textarea,[data-no-translate]");
  const skipAttributes = element => !element || !!element.closest("script,style,code,pre,[data-no-translate]");

  function translateRoot(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      if (!skipElement(root.parentElement)) {
        const next = translate(root.nodeValue);
        if (next !== root.nodeValue) root.nodeValue = next;
      }
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    for (const node of textNodes) {
      if (skipElement(node.parentElement)) continue;
      const next = translate(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    }
    const elements = root.querySelectorAll ? root.querySelectorAll("[aria-label],[title],[placeholder],[alt]") : [];
    for (const element of elements) {
      if (skipAttributes(element)) continue;
      for (const name of ["aria-label", "title", "placeholder", "alt"]) {
        if (!element.hasAttribute(name)) continue;
        const current = element.getAttribute(name);
        const next = translate(current);
        if (next !== current) element.setAttribute(name, next);
      }
    }
  }

  function install() {
    if (!document.documentElement) return;
    document.documentElement.lang = "pt-BR";
    translateRoot(document);
    const observer = new MutationObserver(mutations => {
      const roots = new Set();
      for (const mutation of mutations) {
        if (mutation.type === "characterData") roots.add(mutation.target);
        if (mutation.type === "attributes") roots.add(mutation.target);
        for (const node of mutation.addedNodes) roots.add(node);
      }
      for (const root of roots) translateRoot(root);
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["aria-label", "title", "placeholder", "alt"]
    });
    window.AtticusI18n = { translate, refresh: () => translateRoot(document) };
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", install, { once: true });
